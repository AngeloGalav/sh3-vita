"""Differential test of the x86 -> C translator: each instruction form present in the game is
executed in Unicorn (reference) and via the C generated by x86rec.Func.insn, on random states;
registers, defined flags and touched memory must match.

MMX state (mm0-7) cannot be checked against Unicorn 2.1.4 (register access is a no-op there):
for MMX forms the harness additionally runs a native reference built from <mmintrin.h>
intrinsics (-mmmx, real instructions on the host CPU) on the same input state and compares mm.

Usage : python recomp/difftest.py [cas_par_forme=24] [--keep]
"""
import collections, os, pathlib, random, struct, subprocess, sys

# this repo is the SH3 port: default the recompiler target to sh3 unless overridden
if not any(a == "--target" or a.startswith("--target=") for a in sys.argv[1:]):
    sys.argv[1:1] = ["--target", "sh3"]

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import x86rec
from x86rec import Recompiler, Func, X, h
import unicorn
from unicorn import x86_const as U

ROOT = pathlib.Path(__file__).resolve().parent.parent
GCC = os.environ.get("DIFFTEST_CC", "gcc")  # self-contained harness: no x86rt.c, no SDL
OUT = ROOT / "build" / "difftest"
SCRATCH, SCRATCH_SZ = 0x00100000, 0x00100000
REGS = ["eax", "ecx", "edx", "ebx", "esp", "ebp", "esi", "edi"]
UREG = [U.UC_X86_REG_EAX, U.UC_X86_REG_ECX, U.UC_X86_REG_EDX, U.UC_X86_REG_EBX, U.UC_X86_REG_ESP,
        U.UC_X86_REG_EBP, U.UC_X86_REG_ESI, U.UC_X86_REG_EDI]
CF, PF, ZF, SF, OF = 1, 4, 0x40, 0x80, 0x800
ALL = CF | PF | ZF | SF | OF
SKIP = {"call", "ret", "jmp", "jecxz", "int3", "hlt", "ud2", "nop", "wait", "cpuid", "pushfd", "popfd", "leave",
        "pushal", "popal", "std", "cld"}


def defined_flags(mn, ins):
    base = mn.split()[-1]
    if base in ("add", "adc", "sub", "sbb", "cmp", "neg", "cmpsb", "cmpsd", "cmpsw", "scasb", "scasd"):
        return ALL
    if base in ("inc", "dec"):
        return ALL
    if base in ("and", "or", "xor", "test"):
        return ALL
    if base in ("shl", "sal", "shr", "sar", "shld", "shrd"):
        cnt = ins.operands[-1]
        if cnt.type == X.X86_OP_IMM and (cnt.imm & 31) == 1:
            return ALL
        return CF | PF | ZF | SF  # OF undefined if count != 1
    if base in ("rcr", "rcl", "rol", "ror"):
        cnt = ins.operands[-1]
        if cnt.type == X.X86_OP_IMM and (cnt.imm & 31) == 1:
            return CF | OF
        return CF  # OF undefined if count != 1
    if base in ("clc", "cmc"):
        return CF
    if base in ("imul", "mul"):
        return CF | OF
    if base in ("div", "idiv"):
        return 0
    if base in ("bt", "bts"):
        return CF
    if base == "sahf":
        return CF | PF | ZF | SF
    return ALL  # instructions without effect on flags: everything must stay unchanged


def shape(ins):
    ops = []
    for op in ins.operands:
        if op.type == X.X86_OP_REG:
            ops.append(f"r{op.size}" + ("h" if ins.reg_name(op.reg).endswith("h") else ""))
        elif op.type == X.X86_OP_IMM:
            ops.append(f"i{op.size}")
        else:
            m = op.mem
            ops.append(f"m{op.size}{'b' if m.base else ''}{'x' if m.index else ''}{'s' if m.segment else ''}")
    return (ins.mnemonic, tuple(ops), ins.prefix[2])


def interesting(rng):
    return rng.choice([0, 1, 2, 0x7f, 0x80, 0xff, 0x100, 0x7fff, 0x8000, 0xffff, 0x7fffffff, 0x80000000,
                       0xfffffffe, 0xffffffff, rng.getrandbits(32), rng.getrandbits(32), rng.getrandbits(8),
                       rng.getrandbits(16)])


def is_mmx(ins):
    return any(op.type == X.X86_OP_REG and ins.reg_name(op.reg)[:2] == "mm" for op in ins.operands)


def make_case(ins, rng):
    """Initial state: registers, flags, memory blocks (address, bytes), MMX registers (or None)."""
    regs = [interesting(rng) for _ in range(8)]
    regs[4] = SCRATCH + 0x80000 + rng.randrange(0, 0x100) * 4  # esp in the scratch area
    if ins.mnemonic.split()[-1] in ("div", "idiv"):  # avoid #DE: non-zero divisor, small quotient
        regs[2] = rng.getrandbits(8)
    mem = []
    for op in ins.operands:
        if op.type != X.X86_OP_MEM:
            continue
        m = op.mem
        if m.segment:
            return None
        target = SCRATCH + rng.randrange(0x1000, 0x7f000)
        base = ins.reg_name(m.base) if m.base else None
        idx = ins.reg_name(m.index) if m.index else None
        if base and base not in REGS or idx and idx not in REGS:
            return None
        if idx and idx != base:
            if idx == "esp":
                return None
            iv = rng.randrange(0, 64)
            regs[REGS.index(idx)] = iv
        else:
            iv = 0
        if base:
            if base == "esp":
                target = regs[4] + m.disp + (iv * m.scale if idx else 0)
            else:
                bv = (target - m.disp - iv * m.scale) & 0xffffffff
                if idx == base:
                    return None
                regs[REGS.index(base)] = bv
        elif not idx:
            target = m.disp & 0xffffffff
            if not (0x400000 <= target < 0x13e3000):
                return None
        else:
            target = (m.disp + iv * m.scale) & 0xffffffff
            if not (0x400000 <= target < 0x13e3000):
                return None
        lo = (target - 64) & ~3
        mem.append((lo, bytes(rng.getrandbits(8) for _ in range(160))))
    lo = (regs[4] - 64) & ~3
    mem.append((lo, bytes(rng.getrandbits(8) for _ in range(160))))
    if ins.mnemonic.split()[0] in ("rep", "repe", "repne"):
        regs[1] = rng.randrange(0, 6)  # ecx petit
        for r in ("esi", "edi"):
            regs[REGS.index(r)] = SCRATCH + rng.randrange(0x1000, 0x7f000)
            mem.append(((regs[REGS.index(r)] - 64) & ~3, bytes(rng.getrandbits(8) for _ in range(160))))
    elif ins.mnemonic.split()[-1] in ("movsb", "movsd", "movsw", "stosb", "stosd", "stosw", "cmpsb", "cmpsd",
                                      "scasb", "scasd"):
        for r in ("esi", "edi"):
            regs[REGS.index(r)] = SCRATCH + rng.randrange(0x1000, 0x7f000)
            mem.append(((regs[REGS.index(r)] - 64) & ~3, bytes(rng.getrandbits(8) for _ in range(160))))
    flags = rng.getrandbits(32) & ALL | 2
    mm = None
    if is_mmx(ins):
        mm = [rng.choice([rng.getrandbits(64), rng.getrandbits(64), 0, 0xFFFFFFFFFFFFFFFF,
                          0x00FF00FF00FF00FF, 0x7FFF7FFF7FFF7FFF, 0x8000800080008000,
                          0x0000FFFF0000FFFF, 0x0102030405060708, 0xF0E0D0C0B0A09080])
              for _ in range(8)]
    return regs, flags, mem, mm


def run_unicorn(ins, case):
    regs, flags, mem, mm = case
    uc = unicorn.Uc(unicorn.UC_ARCH_X86, unicorn.UC_MODE_32)
    pages = {ins.address & ~0xfff, (ins.address + 15) & ~0xfff}
    for a, b in mem:
        for p in range(a & ~0xfff, (a + len(b) + 0xfff) & ~0xfff, 0x1000):
            pages.add(p)
    for p in sorted(pages):
        try:
            uc.mem_map(p, 0x1000)
        except unicorn.UcError:
            pass
    uc.mem_write(ins.address, bytes(ins.bytes))
    for a, b in mem:
        uc.mem_write(a, b)
    for r, v in zip(UREG, regs):
        uc.reg_write(r, v)
    uc.reg_write(U.UC_X86_REG_EFLAGS, flags)
    # MMX registers are not modeled by Unicorn 2.1.4 (register access is a no-op):
    # the mm state is validated natively instead, see emit_mmx_ref.
    try:
        uc.emu_start(ins.address, ins.address + ins.size, count=1)
    except unicorn.UcError:
        return None
    if uc.reg_read(U.UC_X86_REG_EIP) != ins.address + ins.size and ins.mnemonic.split()[0] not in ("rep", "repe", "repne"):
        return None
    out_regs = [uc.reg_read(r) & 0xffffffff for r in UREG]
    out_mem = [bytes(uc.mem_read(a, len(b))) for a, b in mem]
    return out_regs, uc.reg_read(U.UC_X86_REG_EFLAGS), out_mem, None


def emit_test(rec, ins, n):
    f = Func.__new__(Func)
    f.rec, f.entry, f.insns, f.addrs = rec, ins.address, [ins], {ins.address}
    f.labels, f.switches, f.out, f.flagsrc = set(), {}, [], None
    try:
        f.insn(ins)
    except Exception:
        return None
    body = "\n".join(f.out)
    if "goto" in body or "return" in body or "rt_call" in body or "rt_unimpl" in body:
        return None
    return (f"static void T{n}(CPU *c, uint32_t *fl) {{\n  uint8_t *const mb = g_mem;\n"
            f"  uint32_t eax=c->eax,ecx=c->ecx,edx=c->edx,ebx=c->ebx,esp=c->esp,ebp=c->ebp,esi=c->esi,edi=c->edi;\n"
            f"  uint32_t cf=fl[0],pf=fl[1],zf=fl[2],sf=fl[3],of=fl[4],fa=0,fb=0,fr=0;\n"
            f"  (void)fa;(void)fb;(void)fr;\n{body}\n"
            f"  c->eax=eax;c->ecx=ecx;c->edx=edx;c->ebx=ebx;c->esp=esp;c->ebp=ebp;c->esi=esi;c->edi=edi;\n"
            f"  fl[0]=cf;fl[1]=pf;fl[2]=zf;fl[3]=sf;fl[4]=of;\n}}\n")


def emit_mmx_ref(ins, n):
    """Native reference for MMX forms: <mmintrin.h> intrinsics compiled with -mmmx, so the
    host CPU executes the real instructions (Unicorn 2.1.4 does not model MMX state)."""
    mn = ins.mnemonic.split()[-1]
    ops = ins.operands
    if mn not in {"movq", "pxor", "punpcklbw", "punpckhbw", "paddw", "psraw", "packuswb", "emms"}:
        return None
    for op in ops:
        if op.type == X.X86_OP_REG and ins.reg_name(op.reg)[:2] != "mm":
            return None

    def mem_addr(op):
        m = op.mem
        parts = []
        if m.base:
            parts.append(f"c->{ins.reg_name(m.base)}")
        if m.index:
            parts.append(f"c->{ins.reg_name(m.index)}" + (f"*{m.scale}u" if m.scale != 1 else ""))
        if m.disp or not parts:
            parts.append(h(m.disp))
        return "(uint32_t)(" + "+".join(parts) + ")"

    def ld(op, name):
        if op.type == X.X86_OP_REG:
            return f"__m64 {name}; memcpy(&{name}, &c->mm[{ins.reg_name(op.reg)[2:]}], 8); "
        return f"__m64 {name}; memcpy(&{name}, g_mem + ({mem_addr(op)}), 8); "

    def st(op, expr):
        if op.type == X.X86_OP_REG:
            return f"{{ __m64 r_ = ({expr}); memcpy(&c->mm[{ins.reg_name(op.reg)[2:]}], &r_, 8); }}"
        return f"{{ __m64 r_ = ({expr}); memcpy(g_mem + ({mem_addr(op)}), &r_, 8); }}"

    if mn == "emms":
        body = "_mm_empty();"
    elif mn == "movq":
        body = ld(ops[1], "s_") + st(ops[0], "s_")
    elif mn == "psraw":
        if ops[1].type == X.X86_OP_IMM:
            body = ld(ops[0], "d_") + st(ops[0], f"_mm_srai_pi16(d_, {ops[1].imm & 0xffff})")
        else:
            body = ld(ops[0], "d_") + ld(ops[1], "s_") + st(ops[0], "_mm_sra_pi16(d_, s_)")
    else:
        fn = {"pxor": "_mm_xor_si64", "punpcklbw": "_mm_unpacklo_pi8", "punpckhbw": "_mm_unpackhi_pi8",
              "paddw": "_mm_add_pi16", "packuswb": "_mm_packs_pu16"}[mn]
        body = ld(ops[0], "d_") + ld(ops[1], "s_") + st(ops[0], f"{fn}(d_, s_)")
    return f"static void R{n}(CPU *c) {{\n  {body}\n}}\n"


HARNESS_MAIN = r"""
#include <stdio.h>
#include <stdlib.h>
uint8_t *g_mem; uint32_t g_mem_size;
_Noreturn void rt_unimpl(CPU *c, uint32_t pc, const char *w) { fprintf(stderr, "unimpl %s @%x\n", w, pc); exit(2); }
_Noreturn void rt_bad_jump(CPU *c, uint32_t pc, uint32_t t) { fprintf(stderr, "bad jump\n"); exit(2); }
_Noreturn void rt_div0(CPU *c, uint32_t pc) { fprintf(stderr, "div0\n"); exit(2); }
const struct { uint32_t a; gfn f; } x86_functab[1]; const unsigned x86_functab_n = 0;
const struct { uint32_t slot; gfn f; const char *name; } x86_iat[1]; const unsigned x86_iat_n = 0;
const uint32_t x86_entry = 0;
void gheap_init(uint32_t b, uint32_t s) { (void)b; (void)s; }
uint32_t gheap_alloc(uint32_t s) { (void)s; return 0; } uint32_t gheap_calloc(uint32_t s) { (void)s; return 0; }
uint32_t gheap_alloc_aligned(uint32_t s, uint32_t a) { (void)s; (void)a; return 0; }
void rt_platform_fatal(const char *m) { fprintf(stderr, "%s\n", m); }
int main(int argc, char **argv) {
  g_mem_size = 0x14000000u;
  g_mem = calloc(1, g_mem_size);
  FILE *in = fopen(argv[1], "rb"), *out = fopen(argv[2], "wb");
  uint32_t hdr[16];
  while (fread(hdr, 4, 16, in) == 16) {
    uint32_t id = hdr[0], nb = hdr[14], mmx = hdr[15];
    CPU c = {0}; c.fcw = 0x27f;
    memcpy(&c.eax, hdr + 1, 32);
    uint32_t fl[5] = {hdr[9], hdr[10], hdr[11], hdr[12], hdr[13]};
    uint8_t mm_in[64];
    if (mmx) {
      if (fread(mm_in, 1, 64, in) != 64) return 1;
      memcpy(c.mm, mm_in, 64);
    }
    uint32_t addr[16], len[16]; uint8_t saved[16][256];
    for (uint32_t i = 0; i < nb; i++) {
      fread(&addr[i], 4, 1, in); fread(&len[i], 4, 1, in);
      fread(g_mem + addr[i], 1, len[i], in); memcpy(saved[i], g_mem + addr[i], len[i]);
    }
    TESTS[id](&c, fl);
    fwrite(&c.eax, 4, 8, out); fwrite(fl, 4, 5, out);
    for (uint32_t i = 0; i < nb; i++) fwrite(g_mem + addr[i], 1, len[i], out);
    if (mmx) {
      fwrite(c.mm, 8, 8, out);  // translated result
      memcpy(c.mm, mm_in, 64);  // same input state for the native reference
      for (uint32_t i = 0; i < nb; i++) memcpy(g_mem + addr[i], saved[i], len[i]);
      REFS[id](&c);
      fwrite(c.mm, 8, 8, out);  // native MMX reference
      for (uint32_t i = 0; i < nb; i++) fwrite(g_mem + addr[i], 1, len[i], out);  // reference memory
    }
  }
  fclose(out);
  return 0;
}
"""


def main():
    per = next((int(a) for a in sys.argv[1:] if a.isdigit()), 24)
    rng = random.Random(1234)
    rec = Recompiler()
    shapes = collections.defaultdict(list)
    for entry, addrs in rec.funcs.items():
        for a in addrs:
            ins = rec.decode(a)
            if not ins:
                continue
            base = ins.mnemonic.split()[-1]
            if base in SKIP or base.startswith("j") or ins.opcode[0] in range(0xD8, 0xE0):
                continue
            k = shape(ins)
            if len(shapes[k]) < 3:
                shapes[k].append(ins)
    tests, cases, refs = [], [], []
    for k, insns in shapes.items():
        for ins in insns:
            code = emit_test(rec, ins, len(tests))
            if not code:
                continue
            tid = len(tests)
            tests.append((code, ins, emit_mmx_ref(ins, tid)))
            for _ in range(per):
                cs = make_case(ins, rng)
                if not cs:
                    continue
                ref = run_unicorn(ins, cs)
                if ref:
                    cases.append((tid, cs))
                    refs.append(ref)
    OUT.mkdir(parents=True, exist_ok=True)
    src = ['#include "x86rt.h"', '#include <mmintrin.h>'] + [c for c, _, _ in tests] + [r for _, _, r in tests if r]
    src.append("static void (*const TESTS[])(CPU *, uint32_t *) = {" + ",".join(f"T{i}" for i in range(len(tests))) + "};")
    src.append("static void Rnone(CPU *c) { (void)c; }")
    src.append("static void (*const REFS[])(CPU *) = {" + ",".join(r[2] and f"R{i}" or "Rnone" for i, r in enumerate(tests)) + "};")
    src.append(HARNESS_MAIN)
    (OUT / "difftest.c").write_text("\n".join(src), encoding="utf-8")
    with open(OUT / "cases.bin", "wb") as f:
        for tid, (regs, flags, mem, mm) in cases:
            fl = [(flags >> 0) & 1, (flags >> 2) & 1, (flags >> 6) & 1, (flags >> 7) & 1, (flags >> 11) & 1]
            f.write(struct.pack("<16I", tid, *regs, *fl, len(mem), 1 if mm else 0))
            if mm:
                f.write(struct.pack("<16I", *[x for v in mm for x in (v & 0xffffffff, v >> 32)]))
            for a, b in mem:
                f.write(struct.pack("<II", a, len(b)) + b)
    exe = OUT / "difftest"
    r = subprocess.run([GCC, "-std=gnu11", "-O1", "-w", "-mmmx", f"-I{ROOT / 'port/src/rt'}",
                        str(OUT / "difftest.c"), "-o", str(exe), "-lm"], capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[:4000])
        return
    subprocess.run([str(exe), str(OUT / "cases.bin"), str(OUT / "out.bin")], check=True)
    data = (OUT / "out.bin").read_bytes()
    pos, fails = 0, collections.Counter()
    examples = {}
    for (tid, (regs, flags, mem, mm)), (ur, uf, um, _) in zip(cases, refs):
        cr = struct.unpack_from("<8I", data, pos); pos += 32
        cfl = struct.unpack_from("<5I", data, pos); pos += 20
        cm = []
        for a, b in mem:
            cm.append(data[pos:pos + len(b)]); pos += len(b)
        cmm = rmm = rm = None
        if mm:
            cmm = list(struct.unpack_from("<8Q", data, pos)); pos += 64
            rmm = list(struct.unpack_from("<8Q", data, pos)); pos += 64
            rm = []
            for a, b in mem:
                rm.append(data[pos:pos + len(b)]); pos += len(b)
        ins = tests[tid][1]
        mask = defined_flags(ins.mnemonic, ins)
        mine = (cfl[0] & 1) | (cfl[1] & 1) << 2 | (cfl[2] & 1) << 6 | (cfl[3] & 1) << 7 | (cfl[4] & 1) << 11
        why = []
        if list(cr) != ur:
            why.append("regs " + " ".join(f"{REGS[i]}:{cr[i]:08x}!={ur[i]:08x}" for i in range(8) if cr[i] != ur[i]))
        if (mine ^ uf) & mask:
            why.append(f"flags {mine & mask:#x} != {uf & mask:#x} (diff {(mine ^ uf) & mask:#x})")
        if mm and cmm != rmm:
            why.append("mmx " + " ".join(f"mm{i}:{cmm[i]:016x}!={rmm[i]:016x}" for i in range(8) if cmm[i] != rmm[i]))
        # for MMX forms Unicorn reads mm as 0, so its memory result is meaningless for
        # store forms: compare memory against the native reference instead
        if cm != (rm if mm else um):
            why.append("memory")
        if why:
            key = f"{ins.mnemonic} {ins.op_str}"
            fails[key] += 1
            examples.setdefault(key, (ins, regs, flags, why))
    total = len(cases)
    print(f"{len(shapes)} shapes, {len(tests)} tests, {total} cases, {sum(fails.values())} failures")
    for k, n in fails.most_common(40):
        ins, regs, flags, why = examples[k]
        print(f"  {n:4}  {k:40} @0x{ins.address:x}  {'; '.join(why)[:150]}")


if __name__ == "__main__":
    main()
